// ISO 국가 코드를 Last.fm 요청에서 순서대로 시도할 국가명 후보로 변환하기 위해 생성했습니다.
export function getCountryNameCandidates(alpha2) {
  if (!alpha2) return []
  const code = alpha2.toUpperCase()

  if (OFFICIAL_OVERRIDES[code]) return OFFICIAL_OVERRIDES[code]
  if (COMMON_NAMES[code]) return [COMMON_NAMES[code]]

  return [code]
}

// ISO 국가 코드를 추천곡 화면에 표시할 읽기 쉬운 국가명으로 변환하기 위해 생성했습니다.
export function getDisplayCountryName(alpha2) {
  if (!alpha2) return ''
  const code = alpha2.toUpperCase()
  if (OFFICIAL_OVERRIDES[code]) {
    return OFFICIAL_OVERRIDES[code][OFFICIAL_OVERRIDES[code].length - 1]
  }
  return COMMON_NAMES[code] ?? code
}
